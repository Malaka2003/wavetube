// Format seconds into MM:SS or HH:MM:SS
function formatDuration(seconds?: number | null): string {
  if (!seconds || isNaN(seconds)) return '--:--';
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  if (hrs > 0) {
    return `${hrs}:${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
  }
  return `${mins}:${secs.toString().padStart(2, '0')}`;
}

// 1. Endpoint: Extract Playlist or Video Information
app.post('/api/playlist/info', async (req, res) => {
  const { url } = req.body;
  if (!url || typeof url !== 'string') {
    return res.status(400).json({ error: 'A valid YouTube playlist or video URL is required.' });
  }

  const cleanUrl = url.trim();
  let parsedUrl: URL;
  try {
    parsedUrl = new URL(cleanUrl);
  } catch {
    return res.status(400).json({ error: 'Please enter a valid YouTube URL.' });
  }
  const allowedHosts = new Set(['youtube.com', 'www.youtube.com', 'm.youtube.com', 'youtu.be', 'music.youtube.com']);
  if (!['http:', 'https:'].includes(parsedUrl.protocol) || !allowedHosts.has(parsedUrl.hostname.toLowerCase())) {
    return res.status(400).json({ error: 'Only YouTube video and playlist URLs are supported.' });
  }

  try {
    await ensureYtDlpBinary();

    const args = [
      '--dump-single-json',
      '--flat-playlist',
      '--no-warnings',
      '--js-runtimes', `node:${NODE_BIN}`,
    ];

    if (fs.existsSync(COOKIE_FILE) && fs.statSync(COOKIE_FILE).size > 10) {
      args.push('--cookies', COOKIE_FILE);
    }

    args.push(cleanUrl);

    const child = spawn(YTDLP_BIN, args, { maxBuffer: 1024 * 1024 * 50 } as any);
    let stdout = '';
    let stderr = '';

    child.stdout.on('data', (data) => {
      stdout += data.toString();
    });

    child.stderr.on('data', (data) => {
      stderr += data.toString();
    });

    child.on('close', (code) => {
      if (code !== 0) {
        console.error('yt-dlp error:', stderr);
        let errorMsg = 'Failed to extract playlist. Please ensure the link is public or unlisted.';
        if (stderr.includes('Sign in to confirm you’re not a bot') || stderr.includes('--cookies')) {
          errorMsg = 'YOUTUBE_BOT_DETECTED: YouTube is requesting bot verification cookies. Please add your YouTube cookie in Cookie Settings.';
        } else if (stderr.includes('The playlist does not exist') || stderr.includes('does not exist')) {
          errorMsg = 'This YouTube playlist does not exist or has been removed.';
        } else if (stderr.includes('Private video') || stderr.includes('Private playlist')) {
          errorMsg = 'This YouTube playlist is marked as private and cannot be accessed.';
        } else if (stderr.includes('Incomplete YouTube ID') || stderr.includes('not a valid URL')) {
          errorMsg = 'The provided URL does not appear to be a valid YouTube link.';
        }
        return res.status(400).json({ error: errorMsg, details: stderr.slice(0, 300) });
      }

      try {
        const data = JSON.parse(stdout);
        const isPlaylist = data._type === 'playlist' || Array.isArray(data.entries);

        let playlistTitle = data.title || 'YouTube Audio Collection';
        let playlistAuthor = data.uploader || data.channel || data.playlist_uploader || 'YouTube';
        let playlistThumbnail = data.thumbnails?.[data.thumbnails.length - 1]?.url || '';

        let entries: any[] = [];
        if (isPlaylist && Array.isArray(data.entries)) {
          entries = data.entries.filter(Boolean);
        } else {
          entries = [data];
        }

        const tracks = entries.map((entry, index) => {
          const videoId = entry.id || '';
          const title = entry.title || `Track ${index + 1}`;
          const duration = entry.duration || null;
          const channel = entry.channel || entry.uploader || playlistAuthor;
          
          let thumbnail = '';
          if (Array.isArray(entry.thumbnails) && entry.thumbnails.length > 0) {
            thumbnail = entry.thumbnails[entry.thumbnails.length - 1]?.url || '';
          }
          if (!thumbnail && videoId) {
            thumbnail = `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;
          }

          return {
            id: videoId,
            index: index + 1,
            title,
            channel,
            duration,
            durationFormatted: formatDuration(duration),
            thumbnail,
            url: entry.url || (videoId ? `https://www.youtube.com/watch?v=${videoId}` : cleanUrl),
          };
        }).filter(t => Boolean(t.id));

        if (!playlistThumbnail && tracks[0]?.thumbnail) {
          playlistThumbnail = tracks[0].thumbnail;
        }

        return res.json({
          isPlaylist,
          id: data.id || 'playlist',
          title: playlistTitle,
          author: playlistAuthor,
          thumbnail: playlistThumbnail,
          totalTracks: tracks.length,
          tracks,
        });
      } catch (parseErr) {
        console.error('Failed to parse yt-dlp output:', parseErr);
        return res.status(500).json({ error: 'Failed to parse playlist data returned by YouTube extractor.' });
      }
    });
  } catch (err: any) {
    console.error('Extraction error:', err);
    return res.status(500).json({ error: err.message || 'Internal server error while extracting playlist.' });
  }
});

// Helper function to convert a single track
async function convertTrackToWav(
  videoId: string,
  title: string,
  options: { sampleRate: number; bitDepth: number; channels: number }
): Promise<{ filePath: string; fileSize: number }> {
  await ensureYtDlpBinary();

  return new Promise((resolve, reject) => {
    const { sampleRate, bitDepth, channels } = options;
    const safeTitle = sanitizeFilename(title || videoId);
    const filename = `${videoId}_${sampleRate}_${bitDepth}bit_${channels}ch.wav`;
    const targetPath = path.join(WAV_STORAGE_DIR, filename);

    // If file already exists and is valid (> 1000 bytes), return immediately
    if (fs.existsSync(targetPath)) {
      const stats = fs.statSync(targetPath);
      if (stats.size > 1000) {
        return resolve({ filePath: targetPath, fileSize: stats.size });
      }
    }

    const codec = bitDepth === 24 ? 'pcm_s24le' : bitDepth === 32 ? 'pcm_f32le' : 'pcm_s16le';
    const tempTemplate = path.join(WAV_STORAGE_DIR, `temp_${videoId}_${Date.now()}.%(ext)s`);

    const args = [
      '-x',
      '--audio-format', 'wav',
      '--audio-quality', '0',
      '--ffmpeg-location', FFMPEG_BIN,
      '--js-runtimes', `node:${NODE_BIN}`,
      '--postprocessor-args', `ffmpeg:-ar ${sampleRate} -ac ${channels} -acodec ${codec}`,
      '-o', tempTemplate,
    ];

    if (fs.existsSync(COOKIE_FILE) && fs.statSync(COOKIE_FILE).size > 10) {
      args.push('--cookies', COOKIE_FILE);
    }

    args.push(`https://www.youtube.com/watch?v=${videoId}`);

    const child = spawn(YTDLP_BIN, args);
    let stderr = '';

    child.stderr.on('data', (d) => {
      stderr += d.toString();
    });

    child.on('close', (code) => {
      // Find the generated file matching temp_
      const dirFiles = fs.readdirSync(WAV_STORAGE_DIR);
      const generated = dirFiles.find(f => f.startsWith(`temp_${videoId}`) && f.endsWith('.wav'));

      if (code === 0 && generated) {
        const fullGeneratedPath = path.join(WAV_STORAGE_DIR, generated);
        try {
          fs.renameSync(fullGeneratedPath, targetPath);
          const stats = fs.statSync(targetPath);
          return resolve({ filePath: targetPath, fileSize: stats.size });
        } catch (renameErr: any) {
          return reject(new Error('Failed to save converted WAV: ' + renameErr.message));
        }
      } else {
        // Cleanup any partial files
        if (generated) {
          try { fs.unlinkSync(path.join(WAV_STORAGE_DIR, generated)); } catch {}
        }

        if (stderr.includes('Sign in to confirm you’re not a bot') || stderr.includes('--cookies') || stderr.includes('authentication')) {
          return reject(new Error('YOUTUBE_BOT_DETECTED: YouTube requires cookies to bypass bot detection. Please click "Cookie Settings" in the header to add your YouTube cookie.'));
        }

        return reject(new Error(stderr.slice(-300) || 'Audio extraction or WAV conversion failed.'));
      }
    });

    child.on('error', (err) => {
      reject(err);
    });
  });
}

// 2. Endpoint: Convert Single Track
app.post('/api/convert/track', async (req, res) => {
  const { videoId, title, sampleRate = 48000, bitDepth = 16, channels = 2 } = req.body;

  if (!videoId || typeof videoId !== 'string' || !/^[A-Za-z0-9_-]{11}$/.test(videoId)) {
    return res.status(400).json({ error: 'A valid 11-character YouTube video ID is required.' });
  }

  const sRate = Number(sampleRate) || 48000;
  const bDepth = Number(bitDepth) || 16;
  const ch = Number(channels) || 2;
  if (![44100, 48000, 96000].includes(sRate) || ![16, 24, 32].includes(bDepth) || ![1, 2].includes(ch)) {
    return res.status(400).json({ error: 'Unsupported audio settings. Choose 44100/48000/96000 Hz, 16/24/32-bit, and 1 or 2 channels.' });
  }
  const safeTitle = sanitizeFilename(title || videoId);

  try {
    const result = await convertTrackToWav(videoId, title, {
      sampleRate: sRate,
      bitDepth: bDepth,
      channels: ch,
    });

    return res.json({
      success: true,
      videoId,
      title: safeTitle,
      fileSize: result.fileSize,
      downloadUrl: `/api/download/track/${videoId}?title=${encodeURIComponent(safeTitle)}&sr=${sRate}&bd=${bDepth}&ch=${ch}`,
      previewUrl: `/api/preview/audio/${videoId}?sr=${sRate}&bd=${bDepth}&ch=${ch}`,
      sampleRate: sRate,
      bitDepth: bDepth,
      channels: ch,
    });
  } catch (err: any) {
    console.error(`Error converting ${videoId}:`, err);
    return res.status(500).json({ error: err.message || 'Conversion failed' });
  }
});

