app.get('/api/download/track/:videoId', (req, res) => {
  const { videoId } = req.params;
  if (!/^[A-Za-z0-9_-]{11}$/.test(videoId)) return res.status(400).json({ error: 'Invalid video ID.' });
  const title = (req.query.title as string) || videoId;
  const sr = Number(req.query.sr) || 48000;
  const bd = Number(req.query.bd) || 16;
  const ch = Number(req.query.ch) || 2;

  const filename = `${videoId}_${sr}_${bd}bit_${ch}ch.wav`;
  const filePath = path.join(WAV_STORAGE_DIR, filename);

  if (!fs.existsSync(filePath)) {
    return res.status(404).json({ error: 'Converted WAV file not found. Please convert first.' });
  }

  const downloadName = `${sanitizeFilename(title)}.wav`;
  const asciiFallback = downloadName.replace(/[^\x20-\x7E]/g, '_');

  res.setHeader('Content-Type', 'audio/wav');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="${asciiFallback}"; filename*=UTF-8''${encodeURIComponent(downloadName)}`
  );
  const stream = fs.createReadStream(filePath);
  stream.pipe(res);
});

// 4. Endpoint: Audio Preview (supports seeking via Range requests)
app.get('/api/preview/audio/:videoId', (req, res) => {
  const { videoId } = req.params;
  if (!/^[A-Za-z0-9_-]{11}$/.test(videoId)) return res.status(400).send('Invalid video ID');
  const sr = Number(req.query.sr) || 48000;
  const bd = Number(req.query.bd) || 16;
  const ch = Number(req.query.ch) || 2;

  const filename = `${videoId}_${sr}_${bd}bit_${ch}ch.wav`;
  const filePath = path.join(WAV_STORAGE_DIR, filename);

  if (!fs.existsSync(filePath)) {
    return res.status(404).send('Preview audio not ready');
  }

  const stat = fs.statSync(filePath);
  const fileSize = stat.size;
  const range = req.headers.range;

  if (range) {
    const parts = range.replace(/bytes=/, "").split("-");
    const start = parseInt(parts[0], 10);
    const end = parts[1] ? parseInt(parts[1], 10) : fileSize - 1;
    const chunksize = (end - start) + 1;
    const file = fs.createReadStream(filePath, { start, end });
    const head = {
      'Content-Range': `bytes ${start}-${end}/${fileSize}`,
      'Accept-Ranges': 'bytes',
      'Content-Length': chunksize,
      'Content-Type': 'audio/wav',
    };
    res.writeHead(206, head);
    file.pipe(res);
  } else {
    const head = {
      'Content-Length': fileSize,
      'Content-Type': 'audio/wav',
    };
    res.writeHead(200, head);
    fs.createReadStream(filePath).pipe(res);
  }
});

// 5. Endpoint: Download Batch as a single ZIP archive
app.get('/api/download/playlist-zip', async (req, res) => {
  const idsParam = req.query.ids as string;
  const playlistTitle = (req.query.title as string) || 'WaveTube_Playlist';
  const sr = Number(req.query.sr) || 48000;
  const bd = Number(req.query.bd) || 16;
  const ch = Number(req.query.ch) || 2;
  if (![44100, 48000, 96000].includes(sr) || ![16, 24, 32].includes(bd) || ![1, 2].includes(ch)) {
    return res.status(400).json({ error: 'Unsupported audio settings.' });
  }

  if (!idsParam) {
    return res.status(400).json({ error: 'No video IDs specified' });
  }

  // Parse id:title pairs (format: id~title,id~title)
  const items = idsParam.split(',').map((item, idx) => {
    const [id, ...rest] = item.split('~');
    const rawTitle = rest.join('~') || `Track_${idx + 1}`;
    let decodedTitle = rawTitle.trim() || `Track_${idx + 1}`;
    try { decodedTitle = decodeURIComponent(decodedTitle); } catch { /* Keep the original title if malformed. */ }
    return {
      id: id.trim(),
      title: decodedTitle,
      index: idx + 1,
    };
  }).filter(i => /^[A-Za-z0-9_-]{11}$/.test(i.id));

  if (items.length === 0) {
    return res.status(400).json({ error: 'No valid tracks specified for ZIP generation' });
  }

  const zipFilename = `${sanitizeFilename(playlistTitle)}_WAV.zip`;
  const asciiZipFallback = zipFilename.replace(/[^\x20-\x7E]/g, '_');

  res.setHeader('Content-Type', 'application/zip');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="${asciiZipFallback}"; filename*=UTF-8''${encodeURIComponent(zipFilename)}`
  );

  const archive = archiver('zip', {
    zlib: { level: 0 }, // WAV is already uncompressed PCM, so compression is unnecessary.
  });

  archive.on('error', (err: any) => {
    console.error('Archive error:', err);
    if (!res.headersSent) {
      res.status(500).send({ error: err.message });
    }
  });

  archive.pipe(res);

  for (const item of items) {
    const targetFilename = `${item.id}_${sr}_${bd}bit_${ch}ch.wav`;
    const targetPath = path.join(WAV_STORAGE_DIR, targetFilename);

    // If file exists, append to zip
    if (fs.existsSync(targetPath)) {
      const padIdx = String(item.index).padStart(2, '0');
      const inZipName = `${padIdx} - ${sanitizeFilename(item.title)}.wav`;
      archive.file(targetPath, { name: inZipName });
    }
  }

  await archive.finalize();
});

