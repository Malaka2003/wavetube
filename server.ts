// Function to ensure yt-dlp is the 40MB standalone binary with bundled Python 3.11+
function ensureYtDlpBinary(): Promise<void> {
  return new Promise((resolve) => {
    try {
      if (fs.existsSync(YTDLP_BIN)) {
        const stats = fs.statSync(YTDLP_BIN);
        // Standalone PyInstaller binary is ~40MB (>20MB)
        if (stats.size > 5 * 1024 * 1024) {
          return resolve();
        }
      }
    } catch {}

    console.log('Downloading standalone yt-dlp binary (bundles Python 3.11)...');
    const binDir = path.dirname(YTDLP_BIN);
    if (!fs.existsSync(binDir)) {
      fs.mkdirSync(binDir, { recursive: true });
    }

    const curl = spawn('curl', [
      '-L',
      'https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp_linux',
      '-o', YTDLP_BIN,
    ]);

    curl.on('close', (code) => {
      if (code === 0 && fs.existsSync(YTDLP_BIN) && fs.statSync(YTDLP_BIN).size > 5 * 1024 * 1024) {
        fs.chmodSync(YTDLP_BIN, 0o755);
        console.log('Standalone yt-dlp binary installed successfully.');
      } else {
        try { fs.unlinkSync(YTDLP_BIN); } catch {}
        console.error('Could not download a valid yt-dlp binary.');
      }
      resolve();
    });

    curl.on('error', () => {
      resolve();
    });
  });
}

// Helper to parse and convert cookies (handles Netscape format, raw header strings, or JSON)
function parseAndFormatCookies(raw: string): string {
  const trimmed = raw.trim();
  if (trimmed.startsWith('# Netscape') || trimmed.includes('\tTRUE\t') || trimmed.includes('\tFALSE\t')) {
    return trimmed;
  }

  // Parse raw Cookie header string: "KEY1=VAL1; KEY2=VAL2"
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by WaveTube for YouTube Bot Bypass',
    '# http://curl.haxx.se/rfc/cookie_spec.html',
    '',
  ];

  const pairs = trimmed.replace(/^Cookie:\s*/i, '').split(';');
  for (const pair of pairs) {
    const idx = pair.indexOf('=');
    if (idx > -1) {
      const key = pair.slice(0, idx).trim();
      const val = pair.slice(idx + 1).trim();
      if (key && val) {
        lines.push(`.youtube.com\tTRUE\t/\tTRUE\t2147483647\t${key}\t${val}`);
      }
    }
  }

  return lines.join('\n');
}

